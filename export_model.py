import joblib
from pathlib import Path
from sklearn.tree import _tree


MODEL_PATH = "model.pkl"
HEADER_PATH = "esp32_model.h"
SKETCH_PATH = "esp32_fruit_freshness.ino"
SKETCH_DIR = Path("esp32_fruit_freshness")


def export_decision_tree_header(artifact: dict) -> str:
    model = artifact["model"]
    if model.__class__.__name__ != "DecisionTreeClassifier":
        raise TypeError("ESP32 C/C++ export currently supports DecisionTreeClassifier only.")

    tree = model.tree_
    features = artifact["features"]
    classes = list(model.classes_)

    lines = [
        "#pragma once",
        "",
        "// Auto-generated by export_model.py.",
        "// Current dataset model uses only the features listed below.",
        f"// Features: {', '.join(features)}",
        "// Returns \"FRESH\" for EARLY and \"SPOILED\" for LATE.",
        "",
        "static const char* predictFreshness(float mq135, float temperature, float humidity) {",
        "  (void)temperature;",
        "  (void)humidity;",
        "  float features[1] = {mq135};",
    ]

    def emit_node(node_id: int, indent: str) -> None:
        if tree.feature[node_id] == _tree.TREE_UNDEFINED:
            class_index = int(tree.value[node_id][0].argmax())
            class_name = classes[class_index]
            output = artifact["output_labels"][class_name]
            lines.append(f'{indent}return "{output}";')
            return

        feature_index = int(tree.feature[node_id])
        threshold = float(tree.threshold[node_id])
        lines.append(f"{indent}if (features[{feature_index}] <= {threshold:.8f}f) {{")
        emit_node(int(tree.children_left[node_id]), indent + "  ")
        lines.append(f"{indent}}} else {{")
        emit_node(int(tree.children_right[node_id]), indent + "  ")
        lines.append(f"{indent}}}")

    emit_node(0, "  ")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def export_gaussian_nb_header(artifact: dict) -> str:
    model = artifact["model"]
    if model.__class__.__name__ != "GaussianNB":
        raise TypeError("Expected GaussianNB.")

    features = artifact["features"]
    if features != ["MQ135"]:
        raise TypeError("GaussianNB export currently expects the one-feature MQ135 model.")

    classes = list(model.classes_)
    fresh_index = classes.index("EARLY")
    spoiled_index = classes.index("LATE")

    mean_fresh = float(model.theta_[fresh_index][0])
    mean_spoiled = float(model.theta_[spoiled_index][0])
    var_fresh = float(model.var_[fresh_index][0])
    var_spoiled = float(model.var_[spoiled_index][0])
    prior_fresh = float(model.class_prior_[fresh_index])
    prior_spoiled = float(model.class_prior_[spoiled_index])

    return "\n".join(
        [
            "#pragma once",
            "#include <math.h>",
            "",
            "// Auto-generated by export_model.py.",
            "// Current dataset model uses MQ135 only.",
            "// Temperature and humidity are accepted for ESP32 call shape but ignored.",
            "",
            "static float gaussianLogProb(float x, float mean, float variance, float prior) {",
            "  const float twoPi = 6.28318530718f;",
            "  float diff = x - mean;",
            "  return logf(prior) - 0.5f * logf(twoPi * variance) - (diff * diff) / (2.0f * variance);",
            "}",
            "",
            "static const char* predictFreshness(float mq135, float temperature, float humidity) {",
            "  (void)temperature;",
            "  (void)humidity;",
            f"  float freshScore = gaussianLogProb(mq135, {mean_fresh:.8f}f, {var_fresh:.8f}f, {prior_fresh:.8f}f);",
            f"  float spoiledScore = gaussianLogProb(mq135, {mean_spoiled:.8f}f, {var_spoiled:.8f}f, {prior_spoiled:.8f}f);",
            '  return freshScore >= spoiledScore ? "FRESH" : "SPOILED";',
            "}",
            "",
        ]
    )


def export_random_forest_header(artifact: dict) -> str:
    model = artifact["model"]
    if model.__class__.__name__ != "RandomForestClassifier":
        raise TypeError("Expected RandomForestClassifier.")

    features = artifact["features"]
    if features != ["MQ135"]:
        raise TypeError("Random Forest export currently expects the one-feature MQ135 model.")

    classes = list(model.classes_)
    late_index = classes.index("LATE")

    lines = [
        "#pragma once",
        "",
        "// Auto-generated by export_model.py.",
        "// Binary Random Forest model trained with MQ135 only.",
        "// DHT22 temperature and humidity are displayed/logged but not used by this model.",
        f"// Trees: {len(model.estimators_)}",
        f"// Feature order: {', '.join(features)}",
        "",
    ]

    def emit_node(estimator, node_id: int, indent: str) -> None:
        tree = estimator.tree_
        if tree.feature[node_id] == _tree.TREE_UNDEFINED:
            counts = tree.value[node_id][0]
            total = float(counts.sum())
            late_probability = 0.0 if total == 0 else float(counts[late_index] / total)
            lines.append(f"{indent}return {late_probability:.8f}f;")
            return

        threshold = float(tree.threshold[node_id])
        lines.append(f"{indent}if (mq135 <= {threshold:.8f}f) {{")
        emit_node(estimator, int(tree.children_left[node_id]), indent + "  ")
        lines.append(f"{indent}}} else {{")
        emit_node(estimator, int(tree.children_right[node_id]), indent + "  ")
        lines.append(f"{indent}}}")

    for index, estimator in enumerate(model.estimators_):
        lines.append(f"static float tree{index}LateProbability(float mq135) {{")
        emit_node(estimator, 0, "  ")
        lines.append("}")
        lines.append("")

    lines.extend(
        [
            "static float predictLateProbability(float mq135) {",
            "  float lateProbability = 0.0f;",
        ]
    )
    for index in range(len(model.estimators_)):
        lines.append(f"  lateProbability += tree{index}LateProbability(mq135);")
    lines.extend(
        [
            f"  return lateProbability / {len(model.estimators_)}.0f;",
            "}",
            "",
            "static const char* predictStage(float mq135) {",
            '  return predictLateProbability(mq135) >= 0.5f ? "LATE" : "EARLY";',
            "}",
            "",
            "static float predictConfidence(float mq135) {",
            "  float lateProbability = predictLateProbability(mq135);",
            "  return lateProbability >= 0.5f ? lateProbability : 1.0f - lateProbability;",
            "}",
            "",
            "static const char* predictFreshness(float mq135, float temperature, float humidity) {",
            "  (void)temperature;",
            "  (void)humidity;",
            "  return predictStage(mq135);",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def write_esp32_sketch() -> None:
    sketch = """#include <Arduino.h>
#include <DHT.h>
#include "esp32_model.h"

// Adjust these pins for your wiring.
#define MQ135_PIN 34
#define DHT_PIN 4
#define DHT_TYPE DHT22

DHT dht(DHT_PIN, DHT_TYPE);

void setup() {
  Serial.begin(115200);
  dht.begin();
}

void loop() {
  int mq135Raw = analogRead(MQ135_PIN);
  float temperature = dht.readTemperature();
  float humidity = dht.readHumidity();

  const char* prediction = predictStage((float)mq135Raw);
  float lateProbability = predictLateProbability((float)mq135Raw);
  float confidence = predictConfidence((float)mq135Raw);

  Serial.print("MQ135: ");
  Serial.println(mq135Raw);

  Serial.print("Temperature: ");
  if (isnan(temperature)) {
    Serial.println("DHT22 read failed");
  } else {
    Serial.println(temperature);
  }

  Serial.print("Humidity: ");
  if (isnan(humidity)) {
    Serial.println("DHT22 read failed");
  } else {
    Serial.println(humidity);
  }

  Serial.print("Prediction: ");
  Serial.println(prediction);

  Serial.print("LATE probability: ");
  Serial.println(lateProbability, 4);

  Serial.print("Confidence: ");
  Serial.println(confidence, 4);

  Serial.println("---");
  delay(2000);
}
"""
    with open(SKETCH_PATH, "w", encoding="utf-8") as f:
        f.write(sketch)
    SKETCH_DIR.mkdir(exist_ok=True)
    with open(SKETCH_DIR / "esp32_fruit_freshness.ino", "w", encoding="utf-8") as f:
        f.write(sketch)


def main() -> None:
    artifact = joblib.load(MODEL_PATH)
    model_name = artifact["model"].__class__.__name__
    if model_name == "DecisionTreeClassifier":
        header = export_decision_tree_header(artifact)
    elif model_name == "GaussianNB":
        header = export_gaussian_nb_header(artifact)
    elif model_name == "RandomForestClassifier":
        header = export_random_forest_header(artifact)
    else:
        raise TypeError(f"ESP32 export does not support {model_name}.")

    with open(HEADER_PATH, "w", encoding="utf-8") as f:
        f.write(header)
    SKETCH_DIR.mkdir(exist_ok=True)
    with open(SKETCH_DIR / HEADER_PATH, "w", encoding="utf-8") as f:
        f.write(header)
    write_esp32_sketch()
    print(f"Wrote {HEADER_PATH}")
    print(f"Wrote {SKETCH_PATH}")
    print(f"Wrote {SKETCH_DIR / 'esp32_fruit_freshness.ino'}")
    print(f"Wrote {SKETCH_DIR / HEADER_PATH}")
    print("Temperature and humidity are read/displayed but ignored by this ML model.")
    print("Collect DHT22 training data before using those values as model features.")


if __name__ == "__main__":
    main()
