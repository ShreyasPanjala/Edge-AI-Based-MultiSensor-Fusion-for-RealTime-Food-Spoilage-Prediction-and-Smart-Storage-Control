"""Prediction retrieval API endpoints."""

import logging
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from database.database import get_db
from models.schemas import PredictionResponse
from services.storage_service import storage_service

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api", tags=["Predictions"])


@router.get(
    "/prediction",
    response_model=PredictionResponse,
    status_code=status.HTTP_200_OK,
    summary="Get Latest Spoilage Prediction",
    description=(
        "Retrieve the most recent food condition prediction generated by the ML inference engine "
        "along with its timestamp."
    ),
    responses={
        200: {
            "description": "Latest prediction retrieved successfully.",
            "content": {
                "application/json": {
                    "example": {
                        "prediction": "Fresh",
                        "timestamp": "2026-09-22T14:35:10Z",
                    }
                }
            },
        },
        404: {
            "description": "No sensor readings or predictions found in the database.",
            "content": {
                "application/json": {
                    "example": {"detail": "No predictions available. No sensor readings have been recorded."}
                }
            },
        },
    },
)
def get_latest_prediction(
    db: Session = Depends(get_db),
) -> PredictionResponse:
    """Query the most recent prediction recorded in the database."""
    latest = storage_service.get_latest_reading(db)
    if not latest:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No predictions available. No sensor readings have been recorded.",
        )
    return PredictionResponse(
        prediction=latest.prediction,
        timestamp=latest.timestamp,
    )
