"""Prediction retrieval and direct inference API endpoints."""

import logging
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from database.database import get_db
from models.schemas import (
    PredictionResponse,
    SensorData,
    DetailedPredictionResponse,
    ActuatorState,
)
from services.storage_service import storage_service
from services.prediction_service import prediction_service

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api", tags=["Predictions"])


@router.get(
    "/prediction",
    response_model=PredictionResponse,
    status_code=status.HTTP_200_OK,
    summary="Get Latest Spoilage Prediction",
    description=(
        "Retrieve the most recent food condition prediction generated by the ML inference engine "
        "along with its timestamp."
    ),
)
def get_latest_prediction(
    db: Session = Depends(get_db),
) -> PredictionResponse:
    """Query the most recent prediction recorded in the database."""
    latest = storage_service.get_latest_reading(db)
    if not latest:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No predictions available. No sensor readings have been recorded.",
        )
    return PredictionResponse(
        prediction=latest.prediction,
        timestamp=latest.timestamp,
    )


@router.post(
    "/predict",
    response_model=DetailedPredictionResponse,
    status_code=status.HTTP_200_OK,
    summary="Direct ML Inference Query",
    description=(
        "Directly evaluate sensor readings (Temperature, Humidity, MQ135) through the trained "
        "Edge-AI model. Returns continuous probabilities, classification stage, confidence score, "
        "and physical actuator control triggers without necessarily committing to database history."
    ),
)
def predict_directly(data: SensorData) -> DetailedPredictionResponse:
    """Run real-time inference on the provided sensor reading."""
    result = prediction_service.predict_detailed(
        temperature=data.temperature,
        humidity=data.humidity,
        mq135=data.mq135,
    )
    return DetailedPredictionResponse(
        prediction=result["prediction"],
        stage=result["stage"],
        probability_spoiled=result["probability_spoiled"],
        confidence_score=result["confidence_score"],
        mq135_adc=result["mq135_adc"],
        temperature=result["temperature"],
        humidity=result["humidity"],
        threshold=result["threshold"],
        model_name=result["model_name"],
        status=result["status"],
        actuators=ActuatorState(**result["actuators"]),
        storage_assessment=result["storage_assessment"],
    )


@router.get(
    "/prediction/detailed",
    response_model=DetailedPredictionResponse,
    status_code=status.HTTP_200_OK,
    summary="Get Detailed Latest Prediction",
    description="Retrieve full continuous probability, stage, and actuator states for the newest sensor telemetry.",
)
def get_latest_detailed_prediction(
    db: Session = Depends(get_db),
) -> DetailedPredictionResponse:
    """Fetch latest reading from persistent storage and evaluate detailed metrics."""
    latest = storage_service.get_latest_reading(db)
    if not latest:
        # Default fresh baseline if empty
        temp, hum, mq = 14.0, 85.0, 495.0
    else:
        temp, hum, mq = latest.temperature, latest.humidity, latest.mq135

    result = prediction_service.predict_detailed(
        temperature=temp,
        humidity=hum,
        mq135=mq,
    )
    return DetailedPredictionResponse(
        prediction=result["prediction"],
        stage=result["stage"],
        probability_spoiled=result["probability_spoiled"],
        confidence_score=result["confidence_score"],
        mq135_adc=result["mq135_adc"],
        temperature=result["temperature"],
        humidity=result["humidity"],
        threshold=result["threshold"],
        model_name=result["model_name"],
        status=result["status"],
        actuators=ActuatorState(**result["actuators"]),
        storage_assessment=result["storage_assessment"],
    )
